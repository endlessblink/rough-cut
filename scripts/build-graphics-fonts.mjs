// Builds apps/desktop/src/shared/graphics-fonts.generated.mjs: handwriting and
// display fonts embedded as data URIs, because graphic pages run with no
// network (CSP font-src data: only) and these are not installed on Linux.
//
// Usage: node scripts/build-graphics-fonts.mjs <dir with unpacked @fontsource/* packages>
//   e.g. after `npm pack @fontsource/amatic-sc@5.3.0` etc. and extracting each into <dir>/<name>/
// All fonts are OFL-1.1 (Amatic SC, Caveat, Karantina) or Apache-2.0 (Permanent Marker).

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('Pass the folder holding the unpacked @fontsource packages.');

const FONTS = [
  { family: 'Amatic SC', pkg: 'amatic-sc', license: 'OFL-1.1', faces: [['hebrew', 400], ['hebrew', 700], ['latin', 400], ['latin', 700]] },
  { family: 'Karantina', pkg: 'karantina', license: 'OFL-1.1', faces: [['hebrew', 400], ['hebrew', 700], ['latin', 400], ['latin', 700]] },
  { family: 'Caveat', pkg: 'caveat', license: 'OFL-1.1', faces: [['latin', 400], ['latin', 700]] },
  { family: 'Permanent Marker', pkg: 'permanent-marker', license: 'Apache-2.0', faces: [['latin', 400]] },
];
const RANGES = {
  hebrew: 'U+0307-0308,U+0590-05FF,U+200C-2010,U+20AA,U+25CC,U+FB1D-FB4F',
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
};

const rules = [];
for (const font of FONTS) {
  for (const [subset, weight] of font.faces) {
    const file = join(dir, font.pkg, 'package', 'files', `${font.pkg}-${subset}-${weight}-normal.woff2`);
    if (!existsSync(file)) throw new Error(`Missing ${file}`);
    const data = readFileSync(file).toString('base64');
    rules.push(`@font-face{font-family:'${font.family}';font-style:normal;font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${data}) format('woff2');unicode-range:${RANGES[subset]}}`);
  }
}

const out = `// GENERATED by scripts/build-graphics-fonts.mjs — do not edit by hand.
// Handwriting/display fonts for Claude graphics, embedded because graphic pages
// have no network. Licences: ${FONTS.map((f) => `${f.family} (${f.license})`).join(', ')}.
export const GRAPHICS_FONT_FAMILIES = ${JSON.stringify(FONTS.map((f) => ({ family: f.family, hebrew: f.faces.some(([s]) => s === 'hebrew'), weights: [...new Set(f.faces.map(([, w]) => w))] })))};
export const GRAPHICS_FONT_CSS = ${JSON.stringify(rules.join('\n'))};
`;
writeFileSync(join(process.cwd(), 'apps/desktop/src/shared/graphics-fonts.generated.mjs'), out);
console.log(`wrote ${rules.length} faces, ${Math.round(out.length / 1024)} KB`);
